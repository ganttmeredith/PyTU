    sim_interp = interp1d(z, sim_temp, bounds_error=False, fill_value="extrapolate")
    sim_temp_interp = sim_interp(hitu_z)

    # Calculate comparison metrics
    abs_diff = np.abs(sim_temp_interp - hitu_temp)
    rel_diff = 100 * abs_diff / hitu_temp

    metrics = {
        'mean_abs_diff': np.mean(abs_diff),
        'max_abs_diff': np.max(abs_diff),
        'mean_rel_diff': np.mean(rel_diff),
        'rmse': np.sqrt(np.mean((sim_temp_interp - hitu_temp)**2))
    }

    # Plot comparison
    plt.figure(figsize=(10, 6))
    plt.plot(z, sim_temp, 'r-', label='Enhanced Model', linewidth=2)
    plt.plot(hitu_z, hitu_temp, 'b--', label='HITU Simulator', linewidth=2)

    # Highlight pancreas region
