    global z, tissue_layers, att_dB, k_thermal, c_p, density, blood_perfusion

    # Calculate beam intensity profile for focused transducer
    # Using analytical model for spherically focused transducer
    I_focused = np.zeros_like(z)

    # Calculate on-axis intensity distribution for a focused transducer
    # Based on O'Neil's model for spherically focused transducers
    wavelength_cm = (sound_speed_default / frequency) * 100  # wavelength in cm
    k = 2 * np.pi / wavelength_cm  # wave number in cm^-1

    for i, zi in enumerate(z):
        # Distance from transducer, normalized to focal length
        normalized_z = zi / focal_depth

        if zi == 0:  # At transducer surface
            I_focused[i] = I0
        else:
            # Avoid division by zero and other numerical issues
            if abs(normalized_z - 1.0) < 1e-10:  # At focal point
                I_focused[i] = I0 * (k * transducer_radius**2 / focal_depth)**2
            else:
                # Apply O'Neil's formula for on-axis intensity
                I_focused[i] = I0 * (np.sin(k * transducer_radius**2 * (1/zi - 1/focal_depth) / 2))**2

    # Apply tissue attenuation to the focused beam
    for i in range(1, len(z)):
        delta_att = att_dB[i-1] * dz
        I_focused[i] *= 10**(-delta_att/10)

