def run_pulsed_simulation(duty_factor, duration_min):
    """Run a simulation with pulsed ultrasound"""
    print(f"\nRunning {duty_factor*100}% duty factor simulation for {duration_min} minutes...")

    duration_sec = duration_min * 60  # Now single value
    nt = int(duration_sec / dt)

    # Initialize temperature array
    T_pulsed = np.ones_like(z) * 37.0
    T_history_pulsed = np.zeros((len(z), nt))
    T_history_pulsed[:,0] = T_pulsed

    # Calculate pulse timing
    pulse_period = 1.0  # 1 second period for duty cycle
    on_time = pulse_period * duty_factor

    for n in tqdm(range(1, nt)):
        current_time = n * dt
        # Determine if in ON/OFF phase of duty cycle
        if (current_time % pulse_period) < on_time:
            Q_scaled = Q
        else:
            Q_scaled = 0 * Q

        dT = np.zeros_like(T_pulsed)
        for i in range(1, len(z)-1):
            diffusion = kappa[i] * (T_pulsed[i+1] - 2*T_pulsed[i] + T_pulsed[i-1]) / dz_m**2
            perfusion = blood_perfusion[i] * blood_density * blood_specific_heat * (blood_temp - T_pulsed[i]) / (density[i] * c_p[i])
            source = Q_scaled[i] / (density[i] * c_p[i])
            dT[i] = dt * (diffusion + perfusion + source)

        # Boundary conditions
        dT[0] = dT[1]
        dT[-1] = dT[-2]

        T_pulsed += dT
        T_history_pulsed[:,n] = T_pulsed

    # Get maximum temperatures at each minute
    pancreas_indices = np.where((z >= 4.0) & (z <= 6.5))
    time_points = []
    pancreas_temps = []
    overall_temps = []

    # Sample at 1 minute intervals
    for minute in range(1, duration_min + 1):
        idx = int(minute * 60 / dt)
        if idx < nt:
            time_points.append(minute)
            pancreas_temps.append(np.max(T_history_pulsed[pancreas_indices, idx]))
            overall_temps.append(np.max(T_history_pulsed[:, idx]))

    return time_points, pancreas_temps, overall_temps

