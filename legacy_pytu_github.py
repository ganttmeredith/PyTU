def compare_with_hitu_simulator(sim_temp, z):
    """Compare with HITU Simulator data from Zderic paper"""

    # Data extracted from HITU Simulator images (from Zderic's paper)
    hitu_z = np.array([0, 1, 2, 3, 4, 5, 6, 7])
    hitu_temp = np.array([37.0, 37.1, 37.25, 37.55, 37.35, 37.3, 37.25, 37.2])

