# **Section 2: Simulate Diabetic Modifications (Glycation)**
# Apply modifications that simulate glycation on lysine (LYS) and arginine (ARG) residues

def apply_diabetic_modification(universe):
    # Copy structure to modify
    diabetic_universe = universe.copy()

    # Identify glycated amino acids (Lysine and Arginine)
    glycated_residues = diabetic_universe.select_atoms("resname LYS ARG")

    # Apply a small displacement to simulate glycation modification on these residues
    for atom in glycated_residues.atoms:
        atom.position += np.random.normal(0, 0.1, size=3)  # Small random displacement

    return diabetic_universe

# Create diabetic and non-diabetic versions
diabetic_Kir6_2 = apply_diabetic_modification(Kir6_2)
diabetic_IRS1 = apply_diabetic_modification(IRS1)

# **Section 3: Define Ultrasound Simulation Parameters**
frequency = 1e6   # 1 MHz
duty_cycle = 1.0  # 100%
duration = 300    # 5 minutes

# **Section 4: Function to Apply Ultrasound and Measure RMSD Changes**
def apply_ultrasound_effect(universe, frequency, duty_cycle, duration):
    rmsd_changes = []
    original_positions = universe.atoms.positions.copy()

    for t in range(int(duration)):
        # Apply pseudo-oscillatory "force" via atomic displacement (simplification)
        displacement = np.sin(2 * np.pi * frequency * t) * duty_cycle * 0.01
        universe.atoms.positions += displacement  # Oscillate positions
        rmsd_value = rmsd(universe.atoms.positions, original_positions)  # RMSD
        rmsd_changes.append(rmsd_value)
        universe.atoms.positions = original_positions  # Reset positions for next cycle

    return rmsd_changes

# **Section 5: Run Ultrasound Simulation**
