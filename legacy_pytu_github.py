    # Set up parameters
    duration_s = duration_min * 60
    nt_duty = int(duration_s / dt)

    # Initial conditions
    T_duty = np.ones_like(z) * 37.0
    T_history_duty = np.zeros((len(z), min(30000, nt_duty)))  # Limit history size to avoid memory issues
    T_history_duty[:,0] = T_duty

    # Apply duty factor by scaling the heating term
    Q_duty = Q * duty_factor

    # Simplified simulation (scaling heating rather than full pulsing)
    for n in tqdm(range(1, nt_duty)):
        dT = np.zeros_like(T_duty)
        for i in range(1, len(z)-1):
            # Diffusion term
            diffusion = kappa[i] * (T_duty[i+1] - 2*T_duty[i] + T_duty[i-1]) / dz_m**2

            # Perfusion term
            perfusion = blood_perfusion[i] * blood_density * blood_specific_heat * (blood_temp - T_duty[i]) / density[i] / c_p[i]

            # Source term (scaled by duty factor)
            source = Q_duty[i] / (density[i] * c_p[i])

            # Combined temperature change
            dT[i] = dt * (diffusion + perfusion + source)

        # Boundary conditions
        dT[0] = dT[1]
        dT[-1] = dT[-2]

        T_duty = T_duty + dT
        if n < 30000:  # Store in history if within limits
            T_history_duty[:,n] = T_duty

    # Calculate max temperatures
    pancreas_indices = np.where((z >= 4.0) & (z <= 6.5))
